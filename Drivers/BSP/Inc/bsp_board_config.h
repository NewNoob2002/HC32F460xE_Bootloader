/* 已验证的 Boot 板级参数；App 接入前核实各产品板卡差异。 */
#define BSP_POWER_HOLD_ACTIVE_LEVEL        1U
#define BSP_EXTERNAL_WATCHDOG_IDLE_LEVEL   0U
#define BSP_EXTERNAL_WATCHDOG_ACTIVE_LEVEL 1U
#define BSP_EXTERNAL_WATCHDOG_INTERVAL_MS  3000U
#define BSP_EXTERNAL_WATCHDOG_PULSE_MS     1U
#define BSP_EXTERNAL_WATCHDOG_DEADLINE_MS  60000U
#define BSP_STATUS_LED_ACTIVE_LEVEL        1U
#define BSP_STATUS_LED_INACTIVE_LEVEL      0U
